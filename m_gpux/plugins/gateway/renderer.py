"""Render a transparent Modal application from a validated gateway manifest."""

from __future__ import annotations

from typing import Any

from m_gpux.core.ignore import to_recursive_ignore
from m_gpux.plugins.gateway.config import GatewayConfig, GatewayTask


def _py(value: Any) -> str:
    """Return a deterministic Python literal for JSON-compatible values."""
    if value is None:
        return "None"
    if isinstance(value, tuple):
        value = list(value)
    return repr(value)


def _decorator_arguments(task: GatewayTask, image_name: str) -> str:
    values: list[tuple[str, Any]] = [
        ("image", image_name),
        ("gpu", task.gpu),
        ("cpu", task.cpu),
        ("memory", task.memory),
        ("timeout", task.timeout),
        ("retries", task.retries),
        ("max_containers", task.max_containers),
        ("scaledown_window", task.scaledown_window),
        ("name", f"task-{task.name}"),
    ]
    rendered: list[str] = []
    for name, value in values:
        if value is None:
            continue
        rendered_value = value if name == "image" else _py(value)
        rendered.append(f"    {name}={rendered_value},")
    return "\n".join(rendered)


def _render_worker(task: GatewayTask, index: int, config: GatewayConfig) -> str:
    image_name = f"task_image_{index}"
    function_name = f"task_worker_{index}"
    packages = ".pip_install(*" + _py(task.packages) + ")" if task.packages else ""
    return f'''{image_name} = (
    modal.Image.debian_slim(python_version={config.python_version!r})
    {packages}
    .add_local_dir(SOURCE_DIR, remote_path="/workspace", copy=True, ignore=SOURCE_IGNORE)
)


@app.function(
{_decorator_arguments(task, image_name)}
)
def {function_name}(payload: dict):
    return _run_task(
        task_name={task.name!r},
        command={_py(task.command)},
        payload=payload,
        timeout={task.timeout},
        max_output_bytes=MAX_OUTPUT_BYTES,
    )
'''


def render_gateway_app(config: GatewayConfig, secret_name: str) -> str:
    """Create the Python source deployed by ``modal deploy``.

    The generated file contains only the Modal Secret *name*. The credential
    value never appears in source, command arguments, or deployment logs.
    """
    ignores = to_recursive_ignore((*config.excludes, "modal_gateway.py"))
    public_tasks = {
        task.name: {
            "description": task.description,
            "gpu": task.gpu,
            "timeout": task.timeout,
        }
        for task in config.tasks
    }
    workers = "\n\n".join(_render_worker(task, index, config) for index, task in enumerate(config.tasks))
    worker_map = ",\n".join(
        f"    {task.name!r}: task_worker_{index}" for index, task in enumerate(config.tasks)
    )
    # json.dumps is used only for the JSON response metadata; repr keeps the
    # generated module valid Python for tuples and Windows paths.
    public_tasks_literal = repr(public_tasks)

    return f'''# Generated by m-gpux. Edit mgpux.gateway.toml, then redeploy.
import json
import os
import subprocess
import time

import modal

APP_NAME = {config.name!r}
SOURCE_DIR = {str(config.source)!r}
SOURCE_IGNORE = {_py(ignores)}
MAX_INPUT_BYTES = {config.max_input_bytes}
MAX_OUTPUT_BYTES = {config.max_output_bytes}
PUBLIC_TASKS = {public_tasks_literal}

app = modal.App(APP_NAME)
gateway_image = modal.Image.debian_slim(python_version={config.python_version!r}).pip_install("fastapi[standard]")
gateway_secret = modal.Secret.from_name({secret_name!r})
jobs = modal.Dict.from_name(APP_NAME + "-jobs", create_if_missing=True)


def _limited_text(data: bytes, limit: int) -> tuple[str, bool]:
    truncated = len(data) > limit
    if truncated:
        data = data[:limit]
    return data.decode("utf-8", errors="replace"), truncated


def _run_task(task_name: str, command: list[str], payload: dict, timeout: int, max_output_bytes: int) -> dict:
    if not isinstance(payload, dict):
        raise ValueError("payload must be a JSON object")
    encoded = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    env = {{**os.environ, "MGPUX_INPUT_JSON": encoded.decode("utf-8")}}
    started = time.monotonic()
    completed = subprocess.run(
        command,
        input=encoded,
        cwd="/workspace",
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=timeout,
        check=False,
        shell=False,
    )
    stdout, stdout_truncated = _limited_text(completed.stdout, max_output_bytes)
    stderr, stderr_truncated = _limited_text(completed.stderr, max_output_bytes)
    if stdout:
        print(stdout, end="" if stdout.endswith("\\n") else "\\n", flush=True)
    if stderr:
        print(stderr, end="" if stderr.endswith("\\n") else "\\n", flush=True)
    if completed.returncode != 0:
        detail = stderr.strip() or stdout.strip() or "no process output"
        raise RuntimeError(f"task {{task_name!r}} exited {{completed.returncode}}: {{detail[:4000]}}")
    try:
        output = json.loads(stdout)
    except json.JSONDecodeError:
        output = stdout
    return {{
        "task": task_name,
        "output": output,
        "stderr": stderr or None,
        "exit_code": completed.returncode,
        "duration_ms": round((time.monotonic() - started) * 1000, 2),
        "truncated": stdout_truncated or stderr_truncated,
    }}


{workers}


WORKERS = {{
{worker_map}
}}


@app.function(image=gateway_image, secrets=[gateway_secret], timeout=900)
@modal.concurrent(max_inputs=100, target_inputs=80)
@modal.asgi_app()
def gateway():
    import hashlib
    import hmac
    import re
    from datetime import datetime, timezone

    from fastapi import Depends, FastAPI, Header, HTTPException, Request, Security
    from fastapi.responses import JSONResponse
    from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
    from modal.exception import FunctionTimeoutError, OutputExpiredError

    # Every Modal call below uses the ``.aio`` interface: blocking calls inside
    # these async handlers would stall the event loop shared by up to 100
    # concurrent requests (and Modal emits AsyncUsageWarning for them).
    terminal_states = {{"succeeded", "failed", "cancelled", "expired"}}
    job_id_re = re.compile(r"^fc-[A-Za-z0-9]{{1,64}}$")

    api = FastAPI(
        title="m-gpux Compute Gateway",
        version="1.0.0",
        description="Asynchronous access to predeclared Modal compute tasks.",
    )
    bearer = HTTPBearer(auto_error=False)

    def now() -> str:
        return datetime.now(timezone.utc).isoformat(timespec="seconds")

    async def authorize(
        credentials: HTTPAuthorizationCredentials | None = Security(bearer),
        x_api_key: str | None = Header(default=None, alias="X-API-Key"),
    ) -> None:
        expected = os.environ.get("MGPUX_GATEWAY_API_KEY", "")
        supplied = credentials.credentials if credentials else (x_api_key or "")
        if not expected or not supplied or not hmac.compare_digest(supplied, expected):
            raise HTTPException(
                status_code=401,
                detail="missing or invalid API key",
                headers={{"WWW-Authenticate": "Bearer"}},
            )

    async def require_job(job_id: str) -> dict:
        # Only jobs submitted through this gateway are visible; arbitrary
        # FunctionCall IDs from other apps in the workspace are not.
        metadata = await jobs.get.aio("job:" + job_id) if job_id_re.fullmatch(job_id) else None
        if not isinstance(metadata, dict):
            raise HTTPException(status_code=404, detail="job not found or expired")
        return metadata

    async def finish(job_id: str, metadata: dict, status: str, **fields) -> dict:
        final = {{**metadata, "status": status, "finished_at": now(), **fields}}
        await jobs.put.aio("job:" + job_id, final)
        return final

    @api.get("/", include_in_schema=False)
    async def root():
        return {{"name": "m-gpux Compute Gateway", "health": "/health", "docs": "/docs"}}

    @api.get("/health")
    async def health():
        return {{"status": "ok", "app": APP_NAME, "tasks": len(PUBLIC_TASKS)}}

    @api.get("/v1/tasks", dependencies=[Depends(authorize)])
    async def list_tasks():
        return {{"tasks": PUBLIC_TASKS}}

    @api.post("/v1/jobs", status_code=202, dependencies=[Depends(authorize)])
    async def submit_job(request: Request):
        body = await request.body()
        if len(body) > MAX_INPUT_BYTES:
            raise HTTPException(status_code=413, detail=f"request exceeds {{MAX_INPUT_BYTES}} bytes")
        try:
            data = json.loads(body or b"{{}}")
        except (json.JSONDecodeError, UnicodeDecodeError):
            raise HTTPException(status_code=400, detail="request body must be valid JSON") from None
        if not isinstance(data, dict):
            raise HTTPException(status_code=400, detail="request body must be a JSON object")
        task_name = data.get("task")
        payload = data.get("input", {{}})
        if task_name not in WORKERS:
            raise HTTPException(status_code=404, detail="unknown task")
        if not isinstance(payload, dict):
            raise HTTPException(status_code=400, detail="input must be a JSON object")

        idempotency_key = request.headers.get("idempotency-key", "").strip()
        idempotency_slot = None
        if idempotency_key:
            if len(idempotency_key) > 200:
                raise HTTPException(status_code=400, detail="idempotency key is too long")
            digest = hashlib.sha256(idempotency_key.encode("utf-8")).hexdigest()
            idempotency_slot = "idem:" + digest
            reservation = {{"status": "submitting", "submitted_at": now()}}
            if not await jobs.put.aio(idempotency_slot, reservation, skip_if_exists=True):
                existing_id = await jobs.get.aio(idempotency_slot)
                if isinstance(existing_id, str):
                    existing = await jobs.get.aio("job:" + existing_id)
                    if isinstance(existing, dict):
                        return JSONResponse(status_code=200, content={{**existing, "idempotent_replay": True}})
                    raise HTTPException(
                        status_code=409,
                        detail="the job for this idempotency key has expired; retry with a new key",
                    )
                raise HTTPException(
                    status_code=409,
                    detail="an idempotent submission with this key is still being created",
                )

        try:
            call = await WORKERS[task_name].spawn.aio(payload)
        except Exception:
            if idempotency_slot:
                await jobs.pop.aio(idempotency_slot, None)
            raise
        metadata = {{
            "id": call.object_id,
            "task": task_name,
            "status": "running",
            "submitted_at": now(),
        }}
        await jobs.put.aio("job:" + call.object_id, metadata)
        if idempotency_slot:
            await jobs.put.aio(idempotency_slot, call.object_id)
        return metadata

    @api.get("/v1/jobs/{{job_id}}", dependencies=[Depends(authorize)])
    async def get_job(job_id: str):
        metadata = await require_job(job_id)
        if metadata.get("status") in terminal_states:
            return metadata
        try:
            result = await modal.FunctionCall.from_id(job_id).get.aio(timeout=0)
        # Order matters: both errors below subclass TimeoutError, which on its
        # own only means "not finished yet".
        except OutputExpiredError:
            return await finish(
                job_id, metadata, "expired", error="Modal keeps spawned results for 7 days; this one has expired"
            )
        except FunctionTimeoutError:
            timeout = PUBLIC_TASKS.get(metadata.get("task"), {{}}).get("timeout")
            return await finish(job_id, metadata, "failed", error=f"task exceeded its {{timeout}}s timeout")
        except TimeoutError:
            return JSONResponse(status_code=202, content={{**metadata, "status": "running"}})
        except Exception as exc:
            return await finish(job_id, metadata, "failed", error=str(exc)[:4000])
        return await finish(job_id, metadata, "succeeded", result=result)

    @api.get("/v1/jobs/{{job_id}}/logs", dependencies=[Depends(authorize)])
    async def get_job_logs(job_id: str, limit: int = 100):
        await require_job(job_id)
        if not 1 <= limit <= 1_000:
            raise HTTPException(status_code=400, detail="limit must be from 1 to 1000")
        entries = []
        try:
            async for entry in modal.FunctionCall.from_id(job_id).logs.tail.aio(limit):
                entries.append({{
                    "timestamp": entry.timestamp.isoformat(),
                    "source": str(getattr(entry.source, "value", entry.source)),
                    "message": entry.message,
                }})
        except Exception as exc:
            raise HTTPException(status_code=502, detail=f"could not read logs: {{str(exc)[:500]}}") from None
        return {{"id": job_id, "logs": entries}}

    @api.delete("/v1/jobs/{{job_id}}", dependencies=[Depends(authorize)])
    async def cancel_job(job_id: str):
        metadata = await require_job(job_id)
        if metadata.get("status") in terminal_states:
            return metadata
        await modal.FunctionCall.from_id(job_id).cancel.aio(terminate_containers=False)
        return await finish(job_id, metadata, "cancelled")

    return api
'''
